// Compile contracts/PqcKeyStatusChecker.sol with solc 0.8.20 and embed the
// resulting ABI + creation bytecode in src/contract.ts, so the helper page
// can deploy the contract without Remix.
//
// Run: node scripts/compile-contract.mjs
// Re-run after any change to contracts/PqcKeyStatusChecker.sol, then rebuild.
import solc from "solc";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const sourcePath = new URL(
  "../contracts/PqcKeyStatusChecker.sol",
  import.meta.url,
);
const outPath = new URL("../src/contract.ts", import.meta.url);

const source = readFileSync(sourcePath, "utf8");
const sourceHash = createHash("sha256").update(source).digest("hex");

const input = {
  language: "Solidity",
  sources: { "PqcKeyStatusChecker.sol": { content: source } },
  settings: {
    optimizer: { enabled: false },
    outputSelection: {
      "*": { "*": ["abi", "evm.bytecode.object"] },
    },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length > 0) {
  for (const e of errors) console.error(e.formattedMessage ?? e.message);
  process.exit(1);
}
for (const w of output.errors ?? []) {
  if (w.severity === "warning") console.warn(w.formattedMessage ?? w.message);
}

const contract =
  output.contracts["PqcKeyStatusChecker.sol"]["PqcKeyStatusChecker"];
if (!contract) throw new Error("PqcKeyStatusChecker not found in output");
const abi = contract.abi;
const bytecode = `0x${contract.evm.bytecode.object}`;
if (!bytecode || bytecode === "0x") {
  throw new Error("Empty creation bytecode");
}

const ts = `// GENERATED by scripts/compile-contract.mjs — do not edit by hand.
// Source: contracts/PqcKeyStatusChecker.sol (sha256 ${sourceHash})
// Compiler: solc ${solc.version()} (optimizer off).
// The creation bytecode calls the PQC key-status precompile (address
// 0x0000000000000000000000000000000000000a02, embedded by solc as the
// value 0xa02 / PUSH2), so the deployment transaction itself exercises
// the precompile via the constructor.

import type { Abi, Hex } from "viem";

export const CONTRACT_ABI: Abi = ${JSON.stringify(abi, null, 2)};

export const CONTRACT_BYTECODE: Hex = "${bytecode}";
`;

writeFileSync(outPath, ts);
console.log(`solc ${solc.version()}`);
console.log(`source sha256: ${sourceHash}`);
console.log(`ABI entries: ${abi.length}`);
console.log(`creation bytecode: ${bytecode.length / 2 - 1} bytes`);
console.log(`wrote ${outPath.pathname}`);
